/* Findet den Kategorieschlüssel zu einem Wert aus der Adresszeile.
   Versteht auch die früheren Anzeigenamen (?kategorie=Sofas) sowie die
   Bezeichnungen der anderen Sprachen, damit geteilte Verweise gültig bleiben. */
function categoryKeyFrom(value) {
  if (!value) return null;
  const wanted = value.trim().toLowerCase();
  if (CATEGORY_KEYS.includes(wanted)) return wanted;
  for (const key of CATEGORY_KEYS) {
    for (const lang of Object.keys(I18N)) {
      if ((I18N[lang]["cat." + key] || "").toLowerCase() === wanted) return key;
    }
  }
  return null;
}

/* --- Zugriff auf die Sprache --- */
const LANG_KEY = "maison-noir-lang";

function getLang() {
  let stored = null;
  try { stored = localStorage.getItem(LANG_KEY); } catch (e) { /* privater Modus */ }
  if (stored && I18N[stored]) return stored;
  const browser = (navigator.language || "de").slice(0, 2).toLowerCase();
  return I18N[browser] ? browser : "de";
}

function setLang(code) {
  if (!I18N[code]) return;
  try { localStorage.setItem(LANG_KEY, code); } catch (e) { /* privater Modus */ }
  location.reload();
}

function langLocale(lang) {
  const l = LANGS.find((x) => x.code === (lang || getLang()));
  return l ? l.locale : "de-DE";
}

/* Übersetzt einen Schlüssel; {platzhalter} werden ersetzt.
   Mit „lang“ lässt sich eine andere Sprache als die eingestellte wählen —
   der Berater antwortet damit in der Sprache der Frage. */
function t(key, vars, lang) {
  const dict = (lang && I18N[lang]) || I18N[getLang()] || I18N.de;
  let str = dict[key];
  if (str === undefined) str = (I18N.de[key] !== undefined ? I18N.de[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => { str = str.split("{" + k + "}").join(vars[k]); });
  }
  return str;
}

/* Setzt alle im HTML ausgezeichneten Texte. */
function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  scope.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  scope.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  scope.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  scope.querySelectorAll("[data-i18n-content]").forEach((el) => { el.content = t(el.dataset.i18nContent); });
  document.documentElement.lang = t("html.lang");
}
